package caddy

import (
	"strings"
	"testing"

	"github.com/isaced/nanoku/internal/db"
)

func TestRender_EmptySites(t *testing.T) {
	out := Render(nil, "")
	if !strings.Contains(out, "Auto-generated by Nanoku") {
		t.Errorf("missing header comment, got:\n%s", out)
	}
	if !strings.Contains(out, "auto_https off") {
		t.Errorf("default should disable auto_https for local-dev friendliness, got:\n%s", out)
	}
}

func TestRender_DisabledSitesAreSkipped(t *testing.T) {
	sites := []*db.Site{
		{Domain: "a.example.com", Upstream: "app:3000", Enabled: true},
		{Domain: "b.example.com", Upstream: "app:3001", Enabled: false},
	}
	out := Render(sites, "")
	if !strings.Contains(out, "a.example.com") {
		t.Errorf("enabled site missing:\n%s", out)
	}
	if strings.Contains(out, "b.example.com") {
		t.Errorf("disabled site must be skipped:\n%s", out)
	}
}

func TestRender_SortsByDomain(t *testing.T) {
	sites := []*db.Site{
		{Domain: "zeta.example.com", Upstream: "a:1", Enabled: true},
		{Domain: "alpha.example.com", Upstream: "a:2", Enabled: true},
		{Domain: "mike.example.com", Upstream: "a:3", Enabled: true},
	}
	out := Render(sites, "")
	zi := strings.Index(out, "zeta")
	ai := strings.Index(out, "alpha")
	mi := strings.Index(out, "mike")
	if !(ai < mi && mi < zi) {
		t.Errorf("expected alpha < mike < zeta, got indexes %d/%d/%d in:\n%s", ai, mi, zi, out)
	}
}

func TestRender_ACMEEmail(t *testing.T) {
	out := Render(nil, "ops@example.com")
	if !strings.Contains(out, "email ops@example.com") {
		t.Errorf("acme email not rendered:\n%s", out)
	}
}

func TestRender_AutoHTTPSOn(t *testing.T) {
	t.Setenv("NANOKU_CADDY_AUTO_HTTPS", "true")
	out := Render([]*db.Site{{Domain: "x.example.com", Upstream: "app:80", Enabled: true}}, "")
	if strings.Contains(out, "auto_https off") {
		t.Errorf("auto_https should NOT be off when env is true:\n%s", out)
	}
	if strings.Contains(out, "http://x.example.com") {
		t.Errorf("should not force http:// scheme when auto_https is on:\n%s", out)
	}
}

func TestRender_AutoHTTPSOffAddsHTTPScheme(t *testing.T) {
	out := Render([]*db.Site{{Domain: "x.example.com", Upstream: "app:80", Enabled: true}}, "")
	if !strings.Contains(out, "http://x.example.com") {
		t.Errorf("auto_https off should force http:// scheme:\n%s", out)
	}
	if !strings.Contains(out, "reverse_proxy app:80") {
		t.Errorf("upstream missing:\n%s", out)
	}
}
